        private void configurarTabela() {
        modeloTabela = new DefaultTableModel(
                new Object[]{"ID", "Nome", "Telefone", "Especialidade", "Ativo"}, 0) {
            @Override
            public boolean isCellEditable(int linha, int coluna) {
                return false;
            }
        };
        tblProfissionais.setModel(modeloTabela);
        tblProfissionais.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        tblProfissionais.getColumnModel().getColumn(0).setMaxWidth(60);
        tblProfissionais.getColumnModel().getColumn(4).setMaxWidth(60);
    }

    private void carregarTabela() {
        modeloTabela.setRowCount(0);
        try {
            List<Profissional> profissionais = controller.listar();
            for (Profissional p : profissionais) {
                modeloTabela.addRow(new Object[]{
                    p.getIdProfissional(),
                    p.getNome(),
                    p.getTelefone(),
                    p.getEspecialidade(),
                    p.isAtivo() ? "Sim" : "Não"
                });
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void limparCampos() {
        txtId.setText("");
        txtNome.setText("");
        txtTelefone.setText("");
        txtEspecialidade.setText("");
        chkAtivo.setSelected(true);
        tblProfissionais.clearSelection();
        txtNome.requestFocus();
    }

    private int getIdSelecionado() {
        String id = txtId.getText().trim();
        return id.isEmpty() ? 0 : Integer.parseInt(id);
    }

    /** Converte o valor de uma célula em texto; célula vazia (null) vira "". */
    private String textoDaCelula(int linha, int coluna) {
        Object valor = modeloTabela.getValueAt(linha, coluna);
        return valor == null ? "" : valor.toString();
    }

