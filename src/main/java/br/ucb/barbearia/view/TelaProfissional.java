    private void tblProfissionaisMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblProfissionaisMouseClicked
                int linha = tblProfissionais.getSelectedRow();
        if (linha >= 0) {
            txtId.setText(textoDaCelula(linha, 0));
            txtNome.setText(textoDaCelula(linha, 1));
            txtTelefone.setText(textoDaCelula(linha, 2));
            txtEspecialidade.setText(textoDaCelula(linha, 3));
            chkAtivo.setSelected("Sim".equals(textoDaCelula(linha, 4)));
        }// TODO add your handling code here:
    }//GEN-LAST:event_tblProfissionaisMouseClicked

