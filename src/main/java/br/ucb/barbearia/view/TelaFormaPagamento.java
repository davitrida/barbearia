    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
                if (getIdSelecionado() > 0) {
            JOptionPane.showMessageDialog(this,
                    "Esta forma de pagamento já está cadastrada. Use Alterar, ou clique em Limpar para cadastrar uma nova.");
            return;
        }
        try {
            controller.salvar(txtDescricao.getText());
            JOptionPane.showMessageDialog(this, "Forma de pagamento cadastrada com sucesso!");
            carregarTabela();
            limparCampos();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Atenção", JOptionPane.WARNING_MESSAGE);
        }// TODO add your handling code here:
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
                try {
            controller.alterar(getIdSelecionado(), txtDescricao.getText());
            JOptionPane.showMessageDialog(this, "Forma de pagamento alterada com sucesso!");
            carregarTabela();
            limparCampos();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Atenção", JOptionPane.WARNING_MESSAGE);
        }// TODO add your handling code here:
    }//GEN-LAST:event_btnAlterarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
                int id = getIdSelecionado();
        if (id > 0 && JOptionPane.showConfirmDialog(this,
                "Deseja realmente excluir esta forma de pagamento?", "Confirmar exclusão",
                JOptionPane.YES_NO_OPTION) != JOptionPane.YES_OPTION) {
            return;
        }
        try {
            controller.excluir(id);
            JOptionPane.showMessageDialog(this, "Forma de pagamento excluída com sucesso!");
            carregarTabela();
            limparCampos();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Atenção", JOptionPane.WARNING_MESSAGE);
        }// TODO add your handling code here:
    }//GEN-LAST:event_btnExcluirActionPerformed

