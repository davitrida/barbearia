        private void configurarTabela() {
        modeloTabela = new DefaultTableModel(new Object[]{"ID", "Descrição"}, 0) {
            @Override
            public boolean isCellEditable(int linha, int coluna) {
                return false;
            }
        };
        tblFormas.setModel(modeloTabela);
        tblFormas.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        tblFormas.getColumnModel().getColumn(0).setMaxWidth(60);
    }

    private void carregarTabela() {
        modeloTabela.setRowCount(0);
        try {
            List<FormaPagamento> formas = controller.listar();
            for (FormaPagamento f : formas) {
                modeloTabela.addRow(new Object[]{f.getIdFormaPagamento(), f.getDescricao()});
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void limparCampos() {
        txtId.setText("");
        txtDescricao.setText("");
        tblFormas.clearSelection();
        txtDescricao.requestFocus();
    }

    private int getIdSelecionado() {
        String id = txtId.getText().trim();
        return id.isEmpty() ? 0 : Integer.parseInt(id);
    }
