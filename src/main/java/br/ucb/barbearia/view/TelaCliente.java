        private void configurarTabela() {
        modeloTabela = new DefaultTableModel(
                new Object[]{"ID", "Nome", "Telefone", "E-mail"}, 0) {
            @Override
            public boolean isCellEditable(int linha, int coluna) {
                return false;
            }
        };
        tblClientes.setModel(modeloTabela);
        tblClientes.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        tblClientes.getColumnModel().getColumn(0).setMaxWidth(60);
    }

    private void carregarTabela() {
        modeloTabela.setRowCount(0);
        try {
            List<Cliente> clientes = controller.listar();
            for (Cliente c : clientes) {
                modeloTabela.addRow(new Object[]{
                    c.getIdCliente(), c.getNome(), c.getTelefone(), c.getEmail()
                });
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void limparCampos() {
        txtId.setText("");
        txtNome.setText("");
        txtTelefone.setText("");
        txtEmail.setText("");
        tblClientes.clearSelection();
        txtNome.requestFocus();
    }

    private int getIdSelecionado() {
        String id = txtId.getText().trim();
        return id.isEmpty() ? 0 : Integer.parseInt(id);
    }

