        private void configurarTabela() {
        modeloTabela = new DefaultTableModel(new Object[]{
            "Data", "Hora", "Cliente", "Profissional", "Serviço", "Valor (R$)", "Status", "Pagamento"}, 0) {
            @Override
            public boolean isCellEditable(int linha, int coluna) {
                return false;
            }
        };
        tblRelatorio.setModel(modeloTabela);
    }

    /** Já abre com o mês atual: do dia 1 ao último dia do mês. */
    private void preencherPeriodoPadrao() {
        LocalDate hoje = LocalDate.now();
        LocalDate inicio = hoje.withDayOfMonth(1);
        LocalDate fim = hoje.withDayOfMonth(hoje.lengthOfMonth());
        txtDataInicial.setText(inicio.format(AgendamentoController.FORMATO_DATA));
        txtDataFinal.setText(fim.format(AgendamentoController.FORMATO_DATA));
    }

    private void gerarRelatorio() {
        modeloTabela.setRowCount(0);
        try {
            List<Agendamento> lista = controller.gerar(txtDataInicial.getText(),
                    txtDataFinal.getText(), (String) cmbStatus.getSelectedItem());

            for (Agendamento a : lista) {
                modeloTabela.addRow(new Object[]{
                    a.getData().format(AgendamentoController.FORMATO_DATA),
                    a.getHora().format(AgendamentoController.FORMATO_HORA),
                    a.getCliente().getNome(),
                    a.getProfissional().getNome(),
                    a.getServico().getDescricao(),
                    a.getValor().toString().replace(".", ","),
                    a.getStatus(),
                    a.getFormaPagamento() == null ? "-" : a.getFormaPagamento().getDescricao()
                });
            }

            lblResumo.setText(String.format(
                    "Total: %d   |   Agendados: %d   |   Concluídos: %d   |   Cancelados: %d"
                    + "   |   Faturado (concluídos): R$ %s",
                    lista.size(),
                    controller.contarPorStatus(lista, Agendamento.AGENDADO),
                    controller.contarPorStatus(lista, Agendamento.CONCLUIDO),
                    controller.contarPorStatus(lista, Agendamento.CANCELADO),
                    controller.somarFaturado(lista).setScale(2).toString().replace(".", ",")));

        } catch (Exception e) {
            lblResumo.setText(" ");
            JOptionPane.showMessageDialog(this, e.getMessage(), "Atenção", JOptionPane.WARNING_MESSAGE);
        }
    }

