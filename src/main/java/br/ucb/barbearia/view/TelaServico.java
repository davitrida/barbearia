        private void configurarTabela() {
        modeloTabela = new DefaultTableModel(
                new Object[]{"ID", "Descrição", "Preço (R$)", "Duração (min)"}, 0) {
            @Override
            public boolean isCellEditable(int linha, int coluna) {
                return false;
            }
        };
        tblServicos.setModel(modeloTabela);
        tblServicos.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        tblServicos.getColumnModel().getColumn(0).setMaxWidth(60);
    }

    private void carregarTabela() {
        modeloTabela.setRowCount(0);
        try {
            List<Servico> servicos = controller.listar();
            for (Servico s : servicos) {
                modeloTabela.addRow(new Object[]{
                    s.getIdServico(),
                    s.getDescricao(),
                    s.getPreco().toString().replace(".", ","),
                    s.getDuracaoMin()
                });
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void limparCampos() {
        txtId.setText("");
        txtDescricao.setText("");
        txtPreco.setText("");
        txtDuracao.setText("");
        tblServicos.clearSelection();
        txtDescricao.requestFocus();
    }

    private int getIdSelecionado() {
        String id = txtId.getText().trim();
        return id.isEmpty() ? 0 : Integer.parseInt(id);
    }

